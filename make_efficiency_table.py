# -*- coding: utf-8 -*-
"""
Tables for the efficiency section (R1.1, R3.5) from results/efficiency.csv.
  results/tables/efficiency_full.csv   all 48 configurations (supplementary table)
  results/tables/efficiency_main.csv   compact table for the main text
  results/tables/efficiency_summary.md key ranges quoted in the text

    python make_efficiency_table.py
"""
import os
import pandas as pd
import common

RED = {"none": "-", "bct": "Spectral BCT", "blockcirc": "Block-circulant", "linear": "Learned linear",
       "pca": "PCA", "random": "Random"}
HEAD = {"linear": "Linear", "mlp": "MLP", "kan": "KAN", "kan_ln": "LN+KAN"}
MAIN = [("none", "linear"), ("none", "mlp"), ("none", "kan"), ("bct", "linear"), ("bct", "kan"),
        ("bct", "kan_ln"), ("blockcirc", "linear"), ("linear", "linear"), ("pca", "linear")]


def main():
    e = pd.read_csv(os.path.join(common.RESULT_DIR, "efficiency.csv"))
    out = os.path.join(common.RESULT_DIR, "tables")
    os.makedirs(out, exist_ok=True)
    t = pd.DataFrame({
        "Backbone": e.backbone.map({"vit_b_16": "ViT-B/16", "resnet50": "ResNet50"}),
        "Reducer (d=128)": e.reducer.map(RED), "Head": e["head"].map(HEAD),
        "Module params": e.params_module, "Total params (M)": (e.params_total / 1e6).round(3),
        "Module share of params (%)": e.module_share_of_params_pct.round(3),
        "Module FLOPs (k)": (e.flops_module / 1e3).round(1), "Total GFLOPs": (e.flops_total / 1e9).round(3),
        "Module share of FLOPs (%)": e.module_share_of_flops_pct.round(4),
        "Module CPU-1T b1 (ms)": e.lat_module_cpu1t_b1_ms.round(3),
        "Module GPU b64 (ms)": e.lat_module_gpu_b64_ms.round(3),
        "Model GPU b64 (ms)": e.lat_full_gpu_b64_ms.round(1), "Model GPU b64 IQR": e.lat_full_gpu_b64_iqr.round(1),
        "Peak memory b64 (MiB)": e.peak_mem_mib_b64.round(0)})
    t.to_csv(os.path.join(out, "efficiency_full.csv"), index=False)
    key = list(zip(e.reducer, e["head"]))
    m = t[[k in MAIN for k in key]]
    m.to_csv(os.path.join(out, "efficiency_main.csv"), index=False)

    lines = ["# Efficiency summary (generated by make_efficiency_table.py)\n"]
    for bb, g in e.groupby("backbone"):
        lines.append(f"## {bb}\n"
                     f"- backbone: {g.params_total.iloc[0] - g.params_module.iloc[0]:,} params, "
                     f"{g.flops_backbone.iloc[0] / 1e9:.2f} GFLOPs/sample\n"
                     f"- module share of params: {g.module_share_of_params_pct.min():.3f}-{g.module_share_of_params_pct.max():.3f} %\n"
                     f"- module share of FLOPs: {g.module_share_of_flops_pct.min():.4f}-{g.module_share_of_flops_pct.max():.4f} %\n"
                     f"- whole-model GPU latency, batch 64: {g.lat_full_gpu_b64_ms.min():.1f}-{g.lat_full_gpu_b64_ms.max():.1f} ms "
                     f"(range {100 * (g.lat_full_gpu_b64_ms.max() / g.lat_full_gpu_b64_ms.min() - 1):.1f} % of the fastest)\n"
                     f"- peak memory, batch 64: {g.peak_mem_mib_b64.min():.0f}-{g.peak_mem_mib_b64.max():.0f} MiB\n"
                     f"- module CPU latency (1 thread, batch 1): Linear/MLP heads "
                     f"{g[g['head'].isin(['linear','mlp'])].lat_module_cpu1t_b1_ms.min():.3f}-"
                     f"{g[g['head'].isin(['linear','mlp'])].lat_module_cpu1t_b1_ms.max():.3f} ms, KAN heads "
                     f"{g[g['head'].isin(['kan','kan_ln'])].lat_module_cpu1t_b1_ms.min():.3f}-"
                     f"{g[g['head'].isin(['kan','kan_ln'])].lat_module_cpu1t_b1_ms.max():.3f} ms\n")
    with open(os.path.join(out, "efficiency_summary.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print("\n".join(lines))
    print(m.to_string(index=False))


if __name__ == "__main__":
    main()
